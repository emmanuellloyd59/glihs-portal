def _validate_migration_set(migrations):
    versions = [migration.version for migration in migrations]
    if versions != sorted(set(versions)) or any(version < 1 for version in versions):
        raise MigrationError("Migration versions must be unique, positive and ordered.")
    if any(not migration.name.strip() or not migration.statements for migration in migrations):
        raise MigrationError("Every migration requires a name and at least one statement.")


def apply_postgresql_migrations(connection, migrations=POSTGRESQL_MIGRATIONS):
    """Apply pending migrations atomically and reject drift or unknown history.

    The caller must provide a Psycopg-compatible connection with autocommit off.
    The entire pending batch and its ledger entries commit atomically. Keeping\n    one transaction open also keeps the transaction-scoped advisory lock held\n    until every migration has completed.
    """
    _validate_migration_set(migrations)
    try:
        connection.execute("SELECT pg_advisory_xact_lock(741923610)")
        connection.execute(
            """CREATE TABLE IF NOT EXISTS schema_migrations (
                version INTEGER PRIMARY KEY,
                name TEXT NOT NULL UNIQUE,
                checksum CHAR(64) NOT NULL,
                applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )"""
        )
        columns = {
            row["column_name"]
            for row in connection.execute(
                """SELECT column_name FROM information_schema.columns
                   WHERE table_schema = current_schema()
                     AND table_name = 'schema_migrations'"""
            ).fetchall()
        }
        required = {"version", "name", "checksum", "applied_at"}
        if columns != required:
            raise MigrationError(
                "PostgreSQL migration ledger has an unexpected shape; manual review is required."
            )

        applied = connection.execute(
            "SELECT version, name, checksum FROM schema_migrations ORDER BY version"
        ).fetchall()
        known = {migration.version: migration for migration in migrations}
        applied_versions = [row["version"] for row in applied]
        if applied_versions != list(range(1, len(applied_versions) + 1)):
            raise MigrationError("PostgreSQL migration ledger has a gap or unsupported version order.")

        for row in applied:
            migration = known.get(row["version"])
            if (
                migration is None
                or migration.name != row["name"]
                or migration.checksum != row["checksum"].strip()
            ):
                raise MigrationError(
                    f"Unknown or modified PostgreSQL migration ledger entry: version {row['version']}."
                )

        applied_set = set(applied_versions)
        applied_now = []
        for migration in migrations:
            if migration.version in applied_set:
                continue
            if migration.version != len(applied_set) + 1:
                raise MigrationError("Pending PostgreSQL migrations are not sequential.")
            for statement in migration.statements:
                connection.execute(statement)
            connection.execute(
                """INSERT INTO schema_migrations (version, name, checksum)
                   VALUES (%s, %s, %s)""",
                (migration.version, migration.name, migration.checksum),
            )
            applied_set.add(migration.version)
            applied_now.append(migration.version)
        connection.commit()
        return tuple(applied_now)
    except Exception:
        connection.rollback()
        raise
