"""Versioned, PostgreSQL-native schema migrations.

This module is intentionally separate from the Flask startup path. It is safe to
run against a disposable PostgreSQL database and does not enable PostgreSQL in
the application. Each migration is applied in its own transaction, under a
transaction-scoped advisory lock, with a checksum-protected ledger.
"""
from dataclasses import dataclass
import hashlib


class MigrationError(RuntimeError):
    """Raised when the PostgreSQL migration history is unsafe or inconsistent."""


@dataclass(frozen=True)
class Migration:
    version: int
    name: str
    statements: tuple

    @property
    def checksum(self):
        payload = "\\n-- statement boundary --\\n".join(self.statements)
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()


